#!/usr/bin/env node
// Generate the browser validator and TypeScript wire union from one contract.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const schema = JSON.parse(readFileSync(resolve(root, 'tauri/src/contracts/recall-chat.json'), 'utf8'));
const header = '// Generated by scripts/generate_recall_contract.mjs; do not edit.\n';
const declaration = header + 'export type RecallChatChunk =\n' + Object.entries(schema.variants).map(([tag, fields]) =>
  `  | { type: ${JSON.stringify(tag)}; ${Object.entries(fields).map(([name, type]) => `${name}: ${type === 'object' ? 'Record<string, unknown>' : type}`).join('; ')} }`
).join('\n') + ';\n';
const browser = header + `(() => {
  'use strict';
  const variants = ${JSON.stringify(schema.variants, null, 2)};
  const ignoredProviderTypes = new Set(${JSON.stringify(schema.ignoredProviderTypes)});
  window.MinutesRecallContract = Object.freeze({
    types: Object.freeze(Object.keys(variants)),
    validate(value) {
      if (!value || typeof value !== 'object' || Array.isArray(value) || typeof value.type !== 'string') return 'invalid';
      if (ignoredProviderTypes.has(value.type)) return 'ignored';
      if (!Object.prototype.hasOwnProperty.call(variants, value.type)) return 'unknown';
      for (const [key, type] of Object.entries(variants[value.type])) {
        const optional = key.endsWith('?');
        const field = value[optional ? key.slice(0, -1) : key];
        if (optional && field === undefined) continue;
        if (typeof field !== type || (type === 'object' && (!field || Array.isArray(field)))) return 'invalid';
      }
      return 'valid';
    },
  });
})();
`;
for (const [file, expected] of [
  ['tauri/src/contracts/recall-chat.d.ts', declaration],
  ['tauri/src/scripts/recall-contract.js', browser],
]) {
  if (process.argv.includes('--check')) assert.equal(readFileSync(resolve(root, file), 'utf8'), expected, `${file} is stale; run node scripts/generate_recall_contract.mjs`);
  else writeFileSync(resolve(root, file), expected);
}
console.log(`Recall contract ${process.argv.includes('--check') ? 'current' : 'generated'}`);
